# Numerical validation of winoddsEIF 0.1.0: scalar right-censored outcomes.
#
# Compare the installed public function winprob_scalar() with the original
# scalar simulation estimator on EXACTLY the same generated data, fold
# assignments, ridge penalty and censoring model.
#
# This does NOT run 5,000-replication simulations. It runs one dataset for
# each of two scenarios. It does NOT modify or reinstall the package.
#
# In RStudio, execute the WHOLE FILE using:
#   source(file.choose())
# Select validate_winoddsEIF_scalar.R.
#
# An error stops source() immediately; the final PASS message is printed
# only after all checks have succeeded.

if (!requireNamespace("winoddsEIF", quietly = TRUE)) {
  stop("Please install winoddsEIF before running this validation script.")
}

# The original author-supplied simulation code is bundled with the package.
original_path <- system.file(
  "reproducibility", "scalar_ridge_all_scenarios.R",
  package = "winoddsEIF"
)
if (!nzchar(original_path) || !file.exists(original_path)) {
  stop("Could not locate the original scalar script in winoddsEIF/inst/reproducibility.")
}

# IMPORTANT: the original script ends by executing a sanity check and,
# if RUN_MAIN is TRUE, thousands of replications. Load only definitions.
lines <- readLines(original_path, warn = FALSE)
run_start <- which(grepl("^sanity_check\\(\\)$", trimws(lines)))
if (length(run_start) != 1L || run_start < 2L) {
  stop("Cannot safely identify the start of the original script's run commands.")
}

# Evaluate each original definition inside its own environment. Unlike
# sourcing the full file, this does not execute its simulation driver.
original <- new.env(parent = globalenv())
code <- parse(
  text = paste(lines[seq_len(run_start - 1L)], collapse = "\n"),
  keep.source = FALSE
)
for (expr in code) eval(expr, envir = original)

required_functions <- c("calibrate_censor", "generate_data", "estimate_once")
for (name in required_functions) {
  if (!exists(name, envir = original, inherits = FALSE) ||
      !is.function(get(name, envir = original, inherits = FALSE))) {
    stop("Original scalar function was not loaded: ", name)
  }
}
if (!exists("SCENARIOS", envir = original, inherits = FALSE) ||
    !is.list(original$SCENARIOS)) {
  stop("Original scalar scenario definitions were not loaded.")
}
cat("Original scalar simulation functions loaded successfully.\n")

# Change these settings if desired. The fold seed is the same for both
# implementations; package folds are generated by set.seed(FOLD_SEED)
# followed by sample(rep(seq_len(FOLDS), length.out = N)).
N <- 240L
FOLDS <- 5L
FOLD_SEED <- 2027L
DATA_SEED <- 2031L
SCENARIOS_TO_CHECK <- c("moderate", "strongest")
TOL <- 1e-8

validate_scalar_package <- function() {
  for (scenario in SCENARIOS_TO_CHECK) {
    cat("\n=== Scenario: ", scenario, " ===\n", sep = "")
    p <- original$SCENARIOS[[scenario]]
    if (is.null(p)) stop("Unknown original scenario: ", scenario)
    c0 <- original$calibrate_censor(p)

    # Generate ONE dataset under the original DGP.
    set.seed(DATA_SEED)
    d_original <- original$generate_data(N, p, c0)

    # Make the same validation folds that winprob_scalar() generates.
    set.seed(FOLD_SEED)
    fold <- sample(rep(seq_len(FOLDS), length.out = N))

    # The original simulation estimator. No oracle hazards.
    fit_original <- original$estimate_once(
      d_original, p, c0, fold, oracle = FALSE
    )

    # Convert the ORIGINAL observed data to the public interface.
    # For scalar survival data, Delta=1 represents an observed event;
    # Delta=0 at time=tau represents an event-free revealed outcome.
    d_package <- data.frame(
      A = d_original$A,
      X = d_original$X,
      time = d_original$s,
      status = d_original$Delta
    )

    # Check that public-interface reconstruction preserves revelation R.
    reconstructed_R <- as.integer(
      d_package$status == 1L | d_package$time >= p$tau
    )
    if (!identical(reconstructed_R, d_original$R)) {
      stop("Observed-data conversion changed the revelation indicators.")
    }

    fit_package <- winoddsEIF::winprob_scalar(
      data = d_package,
      tau = p$tau,
      treatment_prob = p$piA,
      folds = FOLDS,
      seed = FOLD_SEED
    )

    reference <- c(
      psi = fit_original$full,
      se_psi = fit_original$se_full,
      plugin = fit_original$plugin,
      ipcw = fit_original$ipcw,
      se_ipcw = fit_original$se_ipcw,
      min_fitted_G = fit_original$min_G,
      min_ess_treated = fit_original$min_ess_treated,
      min_ess_control = fit_original$min_ess_control,
      hazard_fallbacks = fit_original$fallback
    )
    package <- c(
      psi = fit_package$psi,
      se_psi = fit_package$se_psi,
      plugin = fit_package$plugin,
      ipcw = fit_package$ipcw,
      se_ipcw = fit_package$se_ipcw,
      min_fitted_G = fit_package$diagnostics$min_fitted_G,
      min_ess_treated = fit_package$diagnostics$min_effective_n_treated,
      min_ess_control = fit_package$diagnostics$min_effective_n_control,
      hazard_fallbacks = fit_package$diagnostics$hazard_fallbacks
    )

    if (length(reference) != 9L || length(package) != 9L ||
        !identical(names(reference), names(package)) ||
        any(!is.finite(reference)) || any(!is.finite(package))) {
      stop("Missing, nonfinite, or mislabeled comparison quantities for: ", scenario)
    }

    difference <- abs(reference - package)
    comparison <- data.frame(
      quantity = names(reference),
      original = as.numeric(reference),
      package = as.numeric(package),
      absolute_difference = as.numeric(difference),
      row.names = NULL
    )
    print(comparison, digits = 12, row.names = FALSE)

    if (any(difference > TOL)) {
      stop("FAIL: scalar estimator differs from original in scenario: ", scenario,
           "; maximum absolute difference: ", max(difference))
    }
    cat("PASS: all nine quantities agree within tolerance ", TOL, "\n", sep = "")
  }
  cat("\nAll scalar comparisons passed.\n")
  invisible(TRUE)
}

# Calling source() on this file runs the validations and stops on failure.
validate_scalar_package()
